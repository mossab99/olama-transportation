/**
 * Plugin-owned language service.
 *
 * Transportation language is intentionally independent from the WordPress and
 * Olama School languages. English source strings remain the canonical keys.
 */
final class Olama_Transportation_I18n
{
    private static $registered = false;

    public static function register()
    {
        if (self::$registered) {
            return;
        }
        self::$registered = true;
        add_filter('gettext', array(__CLASS__, 'filter_gettext'), 10, 3);
        add_filter('ngettext', array(__CLASS__, 'filter_ngettext'), 10, 5);
    }

    public static function language()
    {
        $settings = get_option('olama_transportation_settings', array());
        $language = isset($settings['language']) ? sanitize_key($settings['language']) : 'en';
        return in_array($language, array('en', 'ar'), true) ? $language : 'en';
    }

    public static function is_rtl()
    {
        return self::language() === 'ar';
    }

    public static function direction()
    {
        return self::is_rtl() ? 'rtl' : 'ltr';
    }

    public static function filter_gettext($translation, $text, $domain)
    {
        return $domain === 'olama-transportation' ? self::translate($text) : $translation;
    }

    public static function filter_ngettext($translation, $single, $plural, $number, $domain)
    {
        if ($domain !== 'olama-transportation') {
            return $translation;
        }
        return self::translate((int) $number === 1 ? $single : $plural);
    }

    public static function translate($text)
    {
        if ($text === null) {
            return '';
        }
        $text = trim((string) $text);
        if ($text === '' || self::language() !== 'ar') {
            return $text;
        }

        $map = self::translations();
        if (isset($map[$text])) {
            return $map[$text];
        }

        // Reuse the common school vocabulary, while forcing Arabic only for the
        // duration of this call. This keeps this plugin's selector independent.
        if (class_exists('Olama_School_Helpers') && method_exists('Olama_School_Helpers', 'translate')) {
            $school_settings = get_option('olama_school_settings', array());
            $force_arabic = static function () use ($school_settings) {
                return array_merge(is_array($school_settings) ? $school_settings : array(), array('default_lang' => 'ar'));
            };
            add_filter('pre_option_olama_school_settings', $force_arabic);
            try {
                $translated = Olama_School_Helpers::translate($text);
            } finally {
                remove_filter('pre_option_olama_school_settings', $force_arabic);
            }
            if ($translated !== $text) {
                return $translated;
            }
        }

        return $text;
    }

